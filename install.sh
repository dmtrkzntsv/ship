#!/bin/sh
# Install ship on a Linux host.
#   curl -fsSL https://github.com/dmtrkzntsv/ship/releases/latest/download/install.sh | sudo sh
# Environment:
#   SHIP_VERSION   release tag to install (default: the latest release)
#   SHIP_BASE_URL  releases base URL (default: https://github.com/dmtrkzntsv/ship/releases)
set -eu

BASE="${SHIP_BASE_URL:-https://github.com/dmtrkzntsv/ship/releases}"
if [ -n "${SHIP_VERSION:-}" ]; then
	URL="$BASE/download/$SHIP_VERSION"
else
	URL="$BASE/latest/download"
fi

die() { echo "install.sh: $*" >&2; exit 1; }

[ "$(uname -s)" = Linux ] || die "Linux only (on macOS: brew install dmtrkzntsv/tap/ship)"
[ "$(id -u)" -eq 0 ] || die "must run as root (pipe to: sudo sh)"

case "$(uname -m)" in
	x86_64) ARCH=amd64 ;;
	aarch64 | arm64) ARCH=arm64 ;;
	armv7l | armv6l) ARCH=arm ;;
	*) die "unsupported architecture: $(uname -m)" ;;
esac

if command -v curl >/dev/null 2>&1; then
	fetch() { curl -fsSL -o "$2" "$1"; }
elif command -v wget >/dev/null 2>&1; then
	fetch() { wget -q -O "$2" "$1"; }
else
	die "need curl or wget"
fi
command -v sha256sum >/dev/null 2>&1 || die "need sha256sum"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
trap 'exit 130' INT TERM

BIN="ship-linux-$ARCH"
echo "Downloading $BIN from $URL"
fetch "$URL/$BIN" "$TMP/$BIN" || die "download of $BIN failed"
fetch "$URL/SHA256SUMS" "$TMP/SHA256SUMS" || die "download of SHA256SUMS failed"

# Verify only the line for our binary; a missing or mismatching line is fatal.
grep "  $BIN\$" "$TMP/SHA256SUMS" >"$TMP/check" || die "$BIN is not listed in SHA256SUMS"
(cd "$TMP" && sha256sum -c check >/dev/null 2>&1) || die "checksum mismatch for $BIN; nothing installed"

install -d /usr/local/bin
install -m 0755 "$TMP/$BIN" /usr/local/bin/ship.new
mv -f /usr/local/bin/ship.new /usr/local/bin/ship
echo "Installed /usr/local/bin/ship"

# Completions are generated by the installed binary; failures are not fatal.
if [ -d /etc/bash_completion.d ]; then
	/usr/local/bin/ship completion bash >/etc/bash_completion.d/ship 2>/dev/null \
		|| rm -f /etc/bash_completion.d/ship
fi
if command -v zsh >/dev/null 2>&1; then
	mkdir -p /usr/local/share/zsh/site-functions
	/usr/local/bin/ship completion zsh >/usr/local/share/zsh/site-functions/_ship 2>/dev/null \
		|| rm -f /usr/local/share/zsh/site-functions/_ship
fi
if command -v fish >/dev/null 2>&1; then
	mkdir -p /etc/fish/completions
	/usr/local/bin/ship completion fish >/etc/fish/completions/ship.fish 2>/dev/null \
		|| rm -f /etc/fish/completions/ship.fish
fi

# config.example.toml is an unverified template (not covered by SHA256SUMS).
if [ ! -e /etc/ship/config.toml ]; then
	mkdir -p /etc/ship
	if fetch "$URL/config.example.toml" "$TMP/config.toml"; then
		install -m 0600 "$TMP/config.toml" /etc/ship/config.toml
		echo "Created /etc/ship/config.toml"
	else
		echo "install.sh: warning: could not fetch config.example.toml; create /etc/ship/config.toml yourself" >&2
	fi
fi

cat <<'MSG'

ship is installed. Next steps:
  1. Put your R2 endpoint, keys and bucket into /etc/ship/config.toml
  2. ship install <project>[/<component>] --version latest
  3. ship status
MSG
